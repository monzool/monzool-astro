import { defineCollection } from 'astro:content';
import { glob } from 'astro/loaders';
import { z } from 'astro/zod';

const blog = defineCollection({
    // Load Markdown and MDX files in the `src/content/blog/` directory.
    loader: glob({ base: './src/content/blog', pattern: '**/*.{md,mdx}' }),
    // Type-check frontmatter using a schema
    schema: ({ image }) =>
        z.object({
            title: z.string(),
            description: z.string(),
            // Transform string to Date object
            pubDate: z.coerce.date(),
            updatedDate: z.coerce.date().optional(),
            heroImage: z.optional(image()),
            slug: z.string().optional(),
        }),
});

const pages = defineCollection({
    // Load Markdown and MDX files in the `src/content/pages/` directory.
    loader: glob({ base: './src/content/pages', pattern: '**/*.{md,mdx}' }),
    // Type-check frontmatter using a schema
    schema: ({ image }) =>
        z.object({
            title: z.string(),
            description: z.string(),
            heroImage: z.optional(image()),
        }),
});

// Comments from the old WordPress site, one file per post (named after the post slug).
// Generated by scripts/convert-wp-comments.mjs.
const comments = defineCollection({
    loader: glob({ base: './src/content/comments', pattern: '**/*.json' }),
    schema: z.object({
        comments: z.array(
            z.object({
                id: z.number(),
                parent: z.number(),
                author: z.string(),
                url: z.string().optional(),
                date: z.coerce.date(),
                content: z.string(),
            }),
        ),
    }),
});

export const collections = { blog, pages, comments };
